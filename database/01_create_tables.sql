-- Fictional policy migration demo. Run with a schema that can create tables.
-- Dates are Oracle DATE values; all identifiers and data are synthetic.

CREATE TABLE SRC_CUSTOMER (
    CUSTOMER_ID   VARCHAR2(20)  NOT NULL,
    CUSTOMER_NAME VARCHAR2(100),
    CONSTRAINT PK_SRC_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE SRC_PRODUCT (
    PRODUCT_CODE VARCHAR2(20)  NOT NULL,
    PRODUCT_TYPE VARCHAR2(50),
    CONSTRAINT PK_SRC_PRODUCT PRIMARY KEY (PRODUCT_CODE)
);

CREATE TABLE SRC_POLICY (
    POLICY_ID              VARCHAR2(30) NOT NULL,
    POLICY_START_DT        DATE         NOT NULL,
    REQUESTED_EFFECTIVE_DT DATE,
    POLICY_STATUS          VARCHAR2(20) NOT NULL,
    CUSTOMER_ID            VARCHAR2(20) NOT NULL,
    PRODUCT_CODE           VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_SRC_POLICY PRIMARY KEY (POLICY_ID),
    CONSTRAINT FK_SRC_POLICY_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES SRC_CUSTOMER (CUSTOMER_ID),
    CONSTRAINT FK_SRC_POLICY_PRODUCT FOREIGN KEY (PRODUCT_CODE)
        REFERENCES SRC_PRODUCT (PRODUCT_CODE),
    CONSTRAINT CK_SRC_POLICY_STATUS CHECK (POLICY_STATUS IN ('ACTIVE', 'PENDING', 'LAPSED'))
);

-- Deliberate retrieval distractor: this similarly named date is archive metadata.
-- No package reads this table, and it is not a source of TGT_POLICY.EFFECTIVE_DATE.
CREATE TABLE SRC_POLICY_ARCHIVE (
    ARCHIVE_ID      NUMBER        NOT NULL,
    POLICY_ID       VARCHAR2(30)  NOT NULL,
    POLICY_START_DT DATE,
    ARCHIVE_REASON  VARCHAR2(100),
    CONSTRAINT PK_SRC_POLICY_ARCHIVE PRIMARY KEY (ARCHIVE_ID)
);

CREATE TABLE STG_POLICY (
    POLICY_NO             VARCHAR2(30) NOT NULL,
    START_DATE            DATE         NOT NULL,
    REQUESTED_START_DATE  DATE,
    POLICY_STATUS         VARCHAR2(20) NOT NULL,
    CUSTOMER_NAME         VARCHAR2(100),
    PRODUCT_TYPE          VARCHAR2(50),
    CONSTRAINT PK_STG_POLICY PRIMARY KEY (POLICY_NO)
);

CREATE TABLE STG_POLICY_TRANSFORMED (
    POLICY_NO                 VARCHAR2(30) NOT NULL,
    CALCULATED_EFFECTIVE_DATE DATE         NOT NULL,
    POLICY_STATUS             VARCHAR2(20) NOT NULL,
    CUSTOMER_NAME             VARCHAR2(100),
    PRODUCT_TYPE              VARCHAR2(50),
    CONSTRAINT PK_STG_POLICY_TRANSFORMED PRIMARY KEY (POLICY_NO)
);

CREATE TABLE TGT_POLICY (
    POLICY_NO      VARCHAR2(30) NOT NULL,
    EFFECTIVE_DATE DATE         NOT NULL,
    POLICY_STATUS  VARCHAR2(20) NOT NULL,
    CUSTOMER_NAME  VARCHAR2(100),
    PRODUCT_TYPE   VARCHAR2(50),
    CONSTRAINT PK_TGT_POLICY PRIMARY KEY (POLICY_NO)
);
